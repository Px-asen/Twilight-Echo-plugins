import assert from 'node:assert/strict';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const base = process.env.RHINE_TEST_URL || 'http://127.0.0.1:5321';
const browser = await chromium.launch({ channel: 'msedge', headless: true });
try {
  const page = await browser.newPage();
  page.on('console', message => { if (message.type() === 'error') console.error(message.text()); });
  await page.route('**/cover-reveal-harness', route => route.fulfill({ contentType: 'text/html', body: '<!doctype html><title>Cover reveal check</title>' }));
  await page.goto(base + '/cover-reveal-harness');
  const checks = await page.evaluate(async () => {
    const atlasSource = await (await fetch('/src/cover-atlas.ts')).text();
    const displayUrl = atlasSource.match(/from "([^"\n]*\/music-cover-display\.ts[^"\n]*)"/)[1];
    const [{ CoverAtlas }, display, THREE] = await Promise.all([
      import('/src/cover-atlas.ts'), import(displayUrl), import('/node_modules/three/build/three.module.js'),
    ]);
    const checks = [];
    const check = (condition, name) => { if (!condition) throw Error(name); checks.push(name); };
    const color = value => {
      const canvas = document.createElement('canvas'); canvas.width = canvas.height = 64;
      const context = canvas.getContext('2d'); context.fillStyle = value; context.fillRect(0, 0, 64, 64);
      return { source: canvas, width: 64, height: 64, decodedSize: 1024 };
    };
    const green = color('#00ff00'), red = color('#ff0000'), blue = color('#0000ff');
    const album = id => ({ id, title: id, album: { id, artist: id, coverUrl: '/original/' + id } });
    const a = album('A'), b = album('B'), late = [];
    display.setUseDefaultCovers(true);
    const atlas = new CoverAtlas(16, 4096, 8);
    atlas.loadImage = url => url.startsWith('/original/')
      ? new Promise(resolve => late.push({ url, resolve })) : Promise.resolve(green);
    await atlas.select(a);
    check(!atlas.selectedReveal.canvas && late.length === 0, 'browsing does not allocate or fetch original artwork');
    const scene = new THREE.Scene(); scene.add(new THREE.AmbientLight(0xffffff, Math.PI), atlas.selected);
    atlas.selected.visible = true;
    const camera = new THREE.OrthographicCamera(-2, 2, 2, -2, .1, 20);
    camera.position.set(.14, 1.85, 6); camera.lookAt(.14, 1.85, 0);
    const renderer = new THREE.WebGLRenderer(); renderer.setSize(128, 128);
    const target = new THREE.WebGLRenderTarget(128, 128), pixel = new Uint8Array(4);
    const pixels = mesh => {
      scene.remove(atlas.selected); scene.add(mesh);
      renderer.setRenderTarget(target); renderer.render(scene, camera);
      renderer.readRenderTargetPixels(target, 64, 64, 1, 1, pixel);
      scene.remove(mesh); return [...pixel];
    };
    const resting = pixels(atlas.selected);
    check(resting.slice(0, 3).join() === '0,255,0', 'GPU renders the default print at rest: ' + resting);
    atlas.prepareReveal(); atlas.updateReveal(1, .12);
    check(atlas.selectedReveal.amount.value === 0, 'slow original keeps the default visible');
    late.shift().resolve(red); await Promise.resolve();
    atlas.updateReveal(1, .12);
    check(Math.abs(atlas.selectedReveal.amount.value - .5) < .00001, 'late image fades in over 240 ms');
    const middle = pixels(atlas.selected);
    check(middle[0] > 120 && middle[0] < 135 && middle[1] > 120 && middle[1] < 135, 'GPU actually blends both images at half progress');
    atlas.updateReveal(1, .12);
    check(pixels(atlas.selected).slice(0, 3).join() === '255,0,0', 'extracted card renders its real cover');
    const texture = atlas.selectedReveal.texture, version = texture.version;
    for (let frame = 0; frame < 60; frame++) atlas.updateReveal(1 - frame / 60, 1 / 60);
    check(texture.version === version, 'animation changes uniforms without canvas uploads');
    atlas.selectedTexture.anisotropy = 2; atlas.updateReveal(1, .24);
    check(texture.anisotropy === 2 && texture.version === version + 1, 'original follows a live quality change once');
    atlas.updateReveal(1, .24);
    check(texture.version === version + 1, 'unchanged quality does not upload the original again');
    atlas.updateReveal(1, .24);
    const snapshot = atlas.selected.clone(); snapshot.visible = true;
    atlas.snapshot(snapshot);
    await atlas.select(b);
    atlas.prepareReveal();
    const pendingB = late.find(request => request.url.endsWith('/B'));
    late.find(request => request.url.endsWith('/A')).resolve(red); await Promise.resolve();
    check(pixels(snapshot).slice(0, 3).join() === '255,0,0', 'returning copy retains the old original independently');
    pendingB.resolve(blue); await Promise.resolve(); atlas.updateReveal(1, .24);
    check(pixels(atlas.selected).slice(0, 3).join() === '0,0,255', 'new selection reveals its own original');
    atlas.updateSnapshotReveal(snapshot, .35, .24);
    const resuming = pixels(snapshot);
    await atlas.select(a, snapshot);
    check(pixels(atlas.selected).join() === resuming.join(), 'reselecting a returning card preserves its exact visible blend');
    atlas.selectedTexture.anisotropy = 4;
    atlas.updateSnapshotReveal(snapshot, .35, .24);
    check(atlas.snapshots.get(snapshot).reveal.texture.anisotropy === 4, 'returning artwork follows a live quality change');
    atlas.updateSnapshotReveal(snapshot, 0, .24);
    check(pixels(snapshot).slice(0, 3).join() === '0,255,0', 'returning copy restores the default before joining the shelf');
    atlas.updateReveal(0, .24);
    check(pixels(atlas.selected).slice(0, 3).join() === '0,255,0', 'interrupted extraction reverses to the default');
    const pendingSelection = atlas.select(album('late')); await pendingSelection;
    atlas.prepareReveal(); const stale = late.at(-1);
    await atlas.select(b); stale.resolve(red); await Promise.resolve();
    check(!atlas.selectedReveal.ready, 'late previous original cannot repaint a new selection');
    atlas.updateReveal(1, .12);
    const missing = late.at(-1); atlas.reset(); missing.resolve(blue); await Promise.resolve();
    check(!atlas.selectedReveal.ready && atlas.selectedReveal.amount.value === 0, 'reset cancels a pending reveal');
    let disposed = 0; texture.addEventListener('dispose', () => disposed++);
    atlas.dispose();
    check(disposed === 1, 'original texture is released with its material');
    const externalAtlas = new CoverAtlas(4, 4096, 8);
    externalAtlas.loadImage = url => Promise.resolve(url === '/theme-default' ? green : undefined);
    externalAtlas.selected.visible = true;
    display.setUseDefaultCovers(false);
    const external = { ...album('outside'), displayCoverFallback: '/theme-default' };
    await externalAtlas.select(external);
    check(pixels(externalAtlas.selected).slice(0, 3).join() === '0,255,0', 'failed external art uses the theme default, not generated text');
    display.setUseDefaultCovers(true);
    await externalAtlas.select({ ...external, id: 'outside-default', album: { ...external.album, id: 'outside-default' } });
    externalAtlas.prepareReveal(); await new Promise(resolve => setTimeout(resolve, 0));
    externalAtlas.updateReveal(1, .24);
    check(pixels(externalAtlas.selected).slice(0, 3).join() === '0,255,0', 'external reveal also retains the theme fallback when real art fails');
    externalAtlas.dispose();
    snapshot.material.dispose(); snapshot.material.map.dispose(); target.dispose(); renderer.dispose();
    return checks;
  });
  assert.ok(checks.length >= 12);
  console.log('Cover reveal passed: ' + checks.join('; ') + '.');
} finally { await browser.close(); }
